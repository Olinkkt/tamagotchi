fn advance(c: char) -> i32 {
    if c == ' ' { SPACE + GAP } else { glyph(c)[0].len() as i32 + GAP }
}

/// Width of `text` in font pixels.
pub fn width(text: &str) -> i32 {
    (text.chars().map(advance).sum::<i32>() - GAP).max(0)
}

/// The ink pixels of `text`, relative to its top-left corner.
pub fn pixels(text: &str) -> Vec<(i32, i32)> {
    let mut out = Vec::new();
    let mut x = 0;
    for c in text.chars() {
        if c != ' ' {
            for (y, row) in glyph(c).iter().enumerate() {
                for (dx, ch) in row.chars().enumerate() {
                    if ch == '#' {
                        out.push((x + dx as i32, y as i32));
                    }
                }
            }
        }
        x += advance(c);
    }
    out
}

/// Split `text` into lines no wider than `max` font pixels, breaking between words.
pub fn wrap(text: &str, max: i32) -> Vec<String> {
    let mut lines: Vec<String> = Vec::new();
    let mut line = String::new();
    for word in text.split_whitespace() {
        let candidate = if line.is_empty() { word.to_string() } else { format!("{line} {word}") };
        if width(&candidate) <= max || line.is_empty() {
            line = candidate;
        } else {
            lines.push(std::mem::replace(&mut line, word.to_string()));
        }
    }
    if !line.is_empty() {
        lines.push(line);
    }
    lines
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_ascii_character_has_a_glyph() {
        let missing = glyph('\u{0}');
        for c in (33u8..127).map(char::from) {
            assert_ne!(glyph(c), missing, "no glyph for {c:?}");
        }
    }

    #[test]
    fn glyphs_are_rectangular_and_fit_the_line() {
        for c in (33u8..127).map(char::from).chain("→·•♥◎✓".chars()) {
            let g = glyph(c);
            assert!(g.len() as i32 <= HEIGHT, "{c:?}");
            assert!(g.iter().all(|r| r.len() == g[0].len()), "{c:?}");
        }
    }

    #[test]
    fn text_is_measured_with_one_pixel_between_letters() {
        assert_eq!(width("A"), 5);
        assert_eq!(width("AB"), 11);
        assert_eq!(width("A B"), 15);
        assert_eq!(width(""), 0);
        assert_eq!(wrap("feed the pet a meal", width("feed the pet")), ["feed the pet", "a meal"]);
        assert_eq!(wrap("", 10), Vec::<String>::new());
    }
}
